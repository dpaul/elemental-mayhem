// Populate the Admin element with every ability across all other elements
export function populateAdminAbilities(): void {
  const adminConfig = HERO_CLASSES.Admin;
  if (!adminConfig) return;

  const seenIds = new Set<string>(adminConfig.abilities.map((a) => a.id));
  const seenNames = new Set<string>(adminConfig.abilities.map((a) => a.name.toLowerCase()));

  for (const [elemKey, heroConfig] of Object.entries(HERO_CLASSES)) {
    if (elemKey === 'Admin') continue;
    for (const ability of heroConfig.abilities) {
      if (!seenIds.has(ability.id) && !seenNames.has(ability.name.toLowerCase())) {
        seenIds.add(ability.id);
        seenNames.add(ability.name.toLowerCase());
        adminConfig.abilities.push({ ...ability });
      }
    }
  }
}

// Execute population immediately so Admin has all powers
populateAdminAbilities();

export function createHeroForElement(element: ElementType): Unit {
  const config = HERO_CLASSES[element] || HERO_CLASSES.Fire;
  const maxHp = config.bonusStats?.maxHp || 100;
  const maxAp = config.bonusStats?.maxAp || 10;

  // Deep copy abilities to prevent state bleed
  const abilities: Ability[] = config.abilities.map((ab) => ({
    ...ab,
    currentCooldown: 0,
  }));

  return {
    id: 'hero',
    name: config.className,
    faction: 'Player',
    avatar: config.avatar,
    coord: { x: 1, y: 1 },
    level: 0,
    stats: {
      maxHp,
      currentHp: maxHp,
      maxAp,
      currentAp: maxAp,
      moveCostPerTile: 1,
      elementalAffinity: config.element,
    },
    abilities,
    statusEffects: [],
    isDead: false,
  };
}
