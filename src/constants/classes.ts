export function createHeroForElement(element: ElementType): Unit {
  const config = HERO_CLASSES[element] || HERO_CLASSES.Fire;
  const maxHp = config.bonusStats?.maxHp || 100;
  const maxAp = config.bonusStats?.maxAp || 6;

  // Deep copy abilities to prevent state bleed
  const abilities: Ability[] = config.abilities.map((ab) => ({
    ...ab,
    currentCooldown: 0,
  }));

  return {
    id: 'hero',
    name: config.className,
    faction: 'Player',
    avatar: config.avatar,
    coord: { x: 1, y: 1 },
    stats: {
      maxHp,
      currentHp: maxHp,
      maxAp,
      currentAp: maxAp,
      moveCostPerTile: 1,
      elementalAffinity: config.element,
    },
    abilities,
    statusEffects: [],
    isDead: false,
  };
}
